package com.simple;

public class Player {
	public String name;
	public String profile;
	public int topscore;
	public int wkt;
	public void setName(String name) {
		this.name = name;
	}
	public void setProfile(String profile) {
		this.profile = profile;
	}
	public void setTopscore(int topscore) {
		this.topscore = topscore;
	}
	public void setWkt(int wkt) {
		this.wkt = wkt;
	}
	

}
